// Powtórka teorii, przewidywanie i interaktywny plac zabaw dla każdego
// zadania ścieżki układu (Flexbox/Grid) — układ „pilot". Wartości i selektory
// w `code` odpowiadają dokładnie temu, co sprawdzają computedStyle zadania
// (layoutPlans w practicalTasks.js).
//
// Kontrakt plansz (patrz TheoryVisual w LessonPilot.jsx):
//   board: { kind: 'flex',       props: → FlexPlayground  }  — kontener .practice
//          { kind: 'flex-items', props: → FlexItemBoard   }  — właściwości dzieci
//          { kind: 'grid',       props: → GridPlayground  }  — siatka .practice
// `visual` (kind 'layout' z PageDiagram) to awaryjny diagram, gdyby plansza
// nie była dostępna — nie jest renderowany, gdy istnieje `board`.
const note = (title, text, kind, variant, code, question, context, predictionCode, trial, answer, extra = {}) => {
  const { quiz, ...rest } = extra;
  return {
    title, text, visual: { kind, variant }, code, question,
    prediction: { context, code: predictionCode, ...(quiz ? { quizQuestion: question, options: quiz } : {}) },
    trial, answer, ...rest,
  };
};

